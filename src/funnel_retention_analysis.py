def analyze_user_acquisition_funnel():
    """Models user progression through ZO Play acquisition & onboarding funnel."""
    funnel_stages = [
        {"Stage": "1. Ad Impressions / Discovery", "Users": 1000000},
        {"Stage": "2. App Store / Play Store Views", "Users": 380000},
        {"Stage": "3. Installs & First Open", "Users": 145000},
        {"Stage": "4. Registration & Profile Setup", "Users": 112000},
        {"Stage": "5. Completed First Game Session", "Users": 89000},
        {"Stage": "6. Day-1 Retained User", "Users": 21360},
        {"Stage": "7. Day-7 Retained User", "Users": 8544},
        {"Stage": "8. Paying User (IAP / Pass)", "Users": 2221}
    ]
    
    records = []
    prev_users = None
    for item in funnel_stages:
        curr_users = item["Users"]
        if prev_users is None:
            stage_conv = 100.0
            dropoff = 0
        else:
            stage_conv = round((curr_users / prev_users) * 100, 2)
            dropoff = prev_users - curr_users
            
        overall_conv = round((curr_users / funnel_stages[0]["Users"]) * 100, 2)
        records.append({
            "Stage": item["Stage"],
            "Users": curr_users,
            "Stage_Conversion_%": stage_conv,
            "Overall_Funnel_Conversion_%": overall_conv,
            "Dropoff_Count": dropoff
        })
        prev_users = curr_users
        
    return records

def retention_decay_model(days=30, alpha=0.18, beta=0.55):
    """
    Fits power-law retention curve R(t) = (1 + alpha * t)^(-beta)
    to project long-term user retention decay on ZO Play.
    """
    records = []
    for day in range(1, days + 1):
        ret_rate = round(((1 + alpha * day) ** (-beta)) * 100.0, 2)
        churn_rate = round(100.0 - ret_rate, 2)
        records.append({
            "Day": day,
            "Retention_Rate_%": ret_rate,
            "Daily_Churn_%": churn_rate
        })
    return records

def quantify_retention_lift_impact(current_d1_ret=18.5, target_d1_ret=25.0, monthly_installs=100000):
    """
    Calculates incremental active users and revenue generated by improving
    Day-1 retention from current baseline to target benchmark.
    """
    incremental_d1_users = monthly_installs * ((target_d1_ret - current_d1_ret) / 100.0)
    avg_arpu = 0.35 # $ per active user per month
    incremental_monthly_revenue = incremental_d1_users * avg_arpu
    incremental_annual_revenue = incremental_monthly_revenue * 12
    
    return {
        "Monthly_Installs": monthly_installs,
        "Current_D1_Retention_%": current_d1_ret,
        "Target_D1_Retention_%": target_d1_ret,
        "Incremental_Retained_D1_Users_Monthly": int(incremental_d1_users),
        "Incremental_Monthly_Revenue_$": round(incremental_monthly_revenue, 2),
        "Incremental_Annual_Revenue_$": round(incremental_annual_revenue, 2)
    }

